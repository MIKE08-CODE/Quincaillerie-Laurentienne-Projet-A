def _expect_integrity_error(db: Session, obj, constraint: str) -> None:
    db.add(obj)
    with pytest.raises(IntegrityError) as excinfo:
        db.commit()
    db.rollback()
    assert excinfo.value.orig.diag.constraint_name == constraint


def test_sku_is_unique(db, make_product):
    make_product("PERC-001")
    _expect_integrity_error(
        db, Product(sku="PERC-001", name_fr="x", name_en="x", price_cents=1), "uq_products_sku"
    )


def test_price_cannot_be_negative(db):
    product = Product(sku="NEG-1", name_fr="x", name_en="x", price_cents=-1)
    _expect_integrity_error(db, product, "ck_products_price_non_negative")


def test_specs_must_be_a_json_object(db):
    product = Product(sku="SPEC-1", name_fr="x", name_en="x", price_cents=1, specs=[1, 2])
    _expect_integrity_error(db, product, "ck_products_specs_is_object")


def test_brand_name_is_unique_ignoring_case(db, make_brand):
    make_brand("Laurentide Pro", "laurentide-pro")
    _expect_integrity_error(db, Brand(name="LAURENTIDE pro", slug="autre"), "uq_brands_name_lower")


def test_brand_and_category_slugs_are_unique_and_well_formed(db, make_brand, make_category):
    make_brand("Castor", "castor")
    _expect_integrity_error(db, Brand(name="Autre", slug="castor"), "uq_brands_slug")
    make_category("outils")
    _expect_integrity_error(db, Category(slug="outils", name_fr="a", name_en="a"), "uq_categories_slug")
    _expect_integrity_error(
        db, Category(slug="Mauvais Slug", name_fr="a", name_en="a"), "ck_categories_slug_format"
    )


def test_category_cannot_be_its_own_parent(db, make_category):
    category = make_category("outils")
    category.parent_id = category.id
    with pytest.raises(IntegrityError) as excinfo:
        db.commit()
    db.rollback()
    assert excinfo.value.orig.diag.constraint_name in (
        "ck_categories_not_own_parent",
        "ck_categories_no_cycle",
    )


def test_category_cycle_is_refused_by_trigger(db, make_category):
    """A > B > C, puis A sous C : refusé par le déclencheur, même en SQL direct."""
    a = make_category("a")
    b = make_category("b", parent=a)
    c = make_category("c", parent=b)
    with pytest.raises(IntegrityError) as excinfo:
        db.execute(text("UPDATE categories SET parent_id = :c WHERE id = :a"), {"c": c.id, "a": a.id})
    db.rollback()
    assert excinfo.value.orig.diag.constraint_name == "ck_categories_no_cycle"


def test_category_with_children_cannot_be_deleted_in_sql(db, make_category):
    parent = make_category("parent")
    make_category("enfant", parent=parent)
    with pytest.raises(IntegrityError):
        db.execute(text("DELETE FROM categories WHERE id = :id"), {"id": parent.id})
    db.rollback()


def test_image_url_must_be_https_and_position_unique(db, make_product):
    product = make_product("IMG-1")
    _expect_integrity_error(
        db, ProductImage(product_id=product.id, url="http://x.example/a.jpg"), "ck_product_images_url_https"
    )
    db.add(ProductImage(product_id=product.id, url="https://x.example/a.jpg", position=0))
    db.commit()
    _expect_integrity_error(
        db,
        ProductImage(product_id=product.id, url="https://x.example/b.jpg", position=0),
        "uq_product_images_product_id",
    )


def test_search_vector_is_generated_and_accent_insensitive(db, make_product):
    make_product("EQ-1", name_fr="Équerre de menuisier", name_en="Carpenter square")
    found = db.scalars(
        text(
            "SELECT sku FROM products WHERE search_vector @@ "
            "(websearch_to_tsquery('public.fr_unaccent', :q) "
            "|| websearch_to_tsquery('public.en_unaccent', :q))"
        ),
        {"q": "equerre"},
    ).all()
    assert found == ["EQ-1"]
